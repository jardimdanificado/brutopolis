static inline uint32_t decode_utf8_char(const char** p_ptr) {
    const uint8_t* p = (const uint8_t*)(*p_ptr);
    if (!*p) return 0;
    
    uint8_t b0 = *p;
    if (b0 < 0x80) {
        (*p_ptr)++;
        return b0;
    }
    
    if ((b0 & 0xE0) == 0xC0) {
        uint8_t b1 = *(p + 1);
        if ((b1 & 0xC0) == 0x80) {
            *p_ptr += 2;
            return ((uint32_t)(b0 & 0x1F) << 6) | (b1 & 0x3F);
        }
    }
    
    if ((b0 & 0xF0) == 0xE0) {
        uint8_t b1 = *(p + 1);
        uint8_t b2 = *(p + 2);
        if ((b1 & 0xC0) == 0x80 && (b2 & 0xC0) == 0x80) {
            *p_ptr += 3;
            return ((uint32_t)(b0 & 0x0F) << 12) | ((uint32_t)(b1 & 0x3F) << 6) | (b2 & 0x3F);
        }
    }
    
    if ((b0 & 0xF8) == 0xF0) {
        uint8_t b1 = *(p + 1);
        uint8_t b2 = *(p + 2);
        uint8_t b3 = *(p + 3);
        if ((b1 & 0xC0) == 0x80 && (b2 & 0xC0) == 0x80 && (b3 & 0xC0) == 0x80) {
            *p_ptr += 4;
            return ((uint32_t)(b0 & 0x07) << 18) | ((uint32_t)(b1 & 0x3F) << 12) | ((uint32_t)(b2 & 0x3F) << 6) | (b3 & 0x3F);
        }
    }
    
    (*p_ptr)++;
    return b0;
}

